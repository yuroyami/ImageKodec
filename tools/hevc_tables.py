#!/usr/bin/env python3
"""
Writes HevcTables.kt, the constant tables of the HEVC decoder in imagekodec-heic, from the text of
ITU-T H.265 itself, so no table is typed by hand.

The tables are the ones the specification gives as data, which nothing derives: today the default
scaling lists of Table 7-6. The script reads the text that `pdftotext -layout` makes of the
07/2024 edition (V10), checks each table's element count, and writes the tables with the SHA-256
of the text it read and the CRC-32 of every table. HevcTablesTest holds the Kotlin file to those
CRCs, so an edit by hand fails.

    pdftotext -layout T-REC-H.265-202407-I.pdf h265.txt
    python3 tools/hevc_tables.py h265.txt > \\
        imagekodec-heic/src/io/github/yuroyami/imagekodec/heic/HevcTables.kt
"""
import hashlib
import re
import sys
import zlib


def table_7_6(text):
    """The two 64-entry default lists of Table 7-6: matrixId 0..2 (intra) and 3..5 (inter)."""
    # The second heading is the table itself; the first is the list of tables.
    starts = [m.end() for m in re.finditer(r"Table 7-6 – Specification of default values of ScalingList", text)]
    if len(starts) < 2:
        raise SystemExit("Table 7-6 not found")
    body = text[starts[1]:text.index("The four-dimensional array ScalingFactor", starts[1])]
    intra, inter = [], []
    for line in body.splitlines():
        m = re.match(r"\s*ScalingList\[ 1\.\.3 \]\[ (0\.\.2|3\.\.5) \]\[ i \]\s+(.*)$", line)
        if not m:
            continue
        values = [int(v) for v in m.group(2).split()]
        if len(values) != 16:
            raise SystemExit(f"Table 7-6: a row of {len(values)} values: {line!r}")
        (intra if m.group(1) == "0..2" else inter).extend(values)
    if len(intra) != 64 or len(inter) != 64:
        raise SystemExit(f"Table 7-6: {len(intra)} and {len(inter)} values, not 64 each")
    return intra, inter


def kotlin_array(name, values, doc):
    rows = [", ".join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16)]
    crc = zlib.crc32(bytes(values)) & 0xFFFFFFFF
    body = ",\n        ".join(rows)
    return (f"    /** {doc} CRC-32 of the bytes: 0x{crc:08X}. */\n"
            f"    val {name}: IntArray = intArrayOf(\n        {body},\n    )\n")


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: hevc_tables.py h265.txt")
    raw = open(sys.argv[1], "rb").read()
    text = raw.decode("utf-8")
    intra, inter = table_7_6(text)
    print("// Generated by tools/hevc_tables.py from the text of ITU-T H.265 (07/2024).")
    print(f"// SHA-256 of the text: {hashlib.sha256(raw).hexdigest()}. Do not edit by hand.")
    print("package io.github.yuroyami.imagekodec.heic")
    print()
    print("/** The constant tables of ITU-T H.265 that nothing derives. */")
    print("internal object HevcTables {")
    print(kotlin_array("DEFAULT_SCALING_INTRA", intra,
                       "Table 7-6: ScalingList[ 1..3 ][ 0..2 ][ i ], the default 8x8 list of intra blocks, in up-right diagonal order."))
    print(kotlin_array("DEFAULT_SCALING_INTER", inter,
                       "Table 7-6: ScalingList[ 1..3 ][ 3..5 ][ i ], the default 8x8 list of inter blocks, in up-right diagonal order.").rstrip("\n"))
    print("}")


if __name__ == "__main__":
    main()

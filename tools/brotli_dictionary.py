#!/usr/bin/env python3
"""Writes imagekodec/src/.../internal/brotli/BrotliDictionary.kt.

The static dictionary of Brotli is RFC 7932 Appendix A: 122784 bytes of words. This script
takes it from the installed libbrotlicommon (BrotliGetDictionary), checks its size and CRC-32,
and writes it zlib-compressed in base64, as tools/av1_tables.py writes the AV1 tables.

    tools/brotli_dictionary.py > imagekodec/src/io/github/yuroyami/imagekodec/internal/brotli/BrotliDictionary.kt
"""
import base64
import ctypes
import ctypes.util
import sys
import zlib

SIZE = 122784
# The CRC-32 of RFC 7932 Appendix A, which BrotliDictionaryTest checks again on every platform.
CRC = 0x5136CB04


class Dictionary(ctypes.Structure):
    _fields_ = [
        ("size_bits_by_length", ctypes.c_uint8 * 32),
        ("offsets_by_length", ctypes.c_uint32 * 32),
        ("data_size", ctypes.c_size_t),
        ("data", ctypes.POINTER(ctypes.c_uint8)),
    ]


def main():
    name = ctypes.util.find_library("brotlicommon") or "libbrotlicommon.so.1"
    lib = ctypes.CDLL(name)
    lib.BrotliGetDictionary.restype = ctypes.POINTER(Dictionary)
    d = lib.BrotliGetDictionary().contents
    data = bytes(d.data[: d.data_size])
    if len(data) != SIZE or zlib.crc32(data) != CRC:
        sys.exit("libbrotlicommon's dictionary is not RFC 7932's")
    text = base64.b64encode(zlib.compress(data, 9)).decode()
    parts = [text[i : i + 60000] for i in range(0, len(text), 60000)]
    print("// Generated by tools/brotli_dictionary.py from RFC 7932 Appendix A, as libbrotlicommon holds it.")
    print("// Do not edit: run the script.")
    print("package io.github.yuroyami.imagekodec.internal.brotli")
    print()
    print("import io.github.yuroyami.imagekodec.internal.flate.Zlib")
    print()
    print("/** The static dictionary of RFC 7932 Appendix A: %d bytes, CRC-32 0x%08X. */" % (SIZE, CRC))
    print("internal object BrotliDictionary {")
    print("    const val SIZE: Int = %d" % SIZE)
    print("    const val CRC32: Long = 0x%08XL" % CRC)
    print()
    print("    /** The words, inflated on first use: most files that reach the decoder never need them. */")
    print("    val data: ByteArray by lazy { Zlib.decompress(base64(%s), maximumSize = SIZE.toLong()) }"
          % " + ".join("PACKED_%d" % i for i in range(len(parts))))
    print()
    print("    private fun base64(text: String): ByteArray {")
    print('        val alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"')
    print("        val digits = IntArray(128) { -1 }")
    print("        for (i in alphabet.indices) digits[alphabet[i].code] = i")
    print("        val clean = text.trimEnd('=')")
    print("        val out = ByteArray(clean.length * 3 / 4)")
    print("        var bits = 0")
    print("        var count = 0")
    print("        var o = 0")
    print("        for (ch in clean) {")
    print("            bits = (bits shl 6) or digits[ch.code]")
    print("            count += 6")
    print("            if (count >= 8) {")
    print("                count -= 8")
    print("                out[o++] = (bits shr count).toByte()")
    print("            }")
    print("        }")
    print("        return out")
    print("    }")
    for i, p in enumerate(parts):
        print()
        print("    private const val PACKED_%d =" % i)
        lines = [p[k : k + 120] for k in range(0, len(p), 120)]
        print("        " + " +\n        ".join('"%s"' % line for line in lines))
    print("}")


if __name__ == "__main__":
    main()

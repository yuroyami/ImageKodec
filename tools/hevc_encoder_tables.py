#!/usr/bin/env python3
"""
Writes HevcEncoderTables.kt, the constant tables of the HEVC encoder in imagekodec-heic, so that no
encoder decision calls a transcendental function at run time and every target gives the same bytes.

- BIT_COST: the cost in 1/256 bits of coding a bin in each CABAC state, from the probability model
  that ITU-T H.265 9.3.4.3.2 builds its state machine on: pLPS( s ) = 0.5 * a^s with
  a = ( 0.01875 / 0.5 )^( 1 / 63 ). Entry 2 * s holds the cost of the most probable symbol and entry
  2 * s + 1 that of the least probable one.
- LAMBDA_Q8 and SQRT_LAMBDA_Q8: the Lagrange multiplier of the rate-distortion decisions for each
  QP of an 8-bit picture, and its square root, in 1/256. The encoder uses
  lambda = 0.57 * 2^( ( QP - 12 ) / 3 ), the exponential relation between the multiplier and the
  quantization step that the H.264 and HEVC rate-distortion literature derives for intra coding.
- MD5_T: the sine table of IETF RFC 1321, section 3.4: the integer part of 2^32 * abs( sin( i ) ).

The script prints the Kotlin file with the CRC-32 of each table, which HevcEncoderTest checks.

    python3 tools/hevc_encoder_tables.py > \\
        imagekodec-heic/src/io/github/yuroyami/imagekodec/heic/HevcEncoderTables.kt
"""
import math
import struct
import zlib


def bit_cost():
    a = (0.01875 / 0.5) ** (1.0 / 63.0)
    out = []
    for s in range(64):
        p_lps = 0.5 * a ** s
        out.append(round(-math.log2(1.0 - p_lps) * 256))
        out.append(round(-math.log2(p_lps) * 256))
    return out


def lambdas():
    lam = [0.57 * 2.0 ** ((qp - 12) / 3.0) for qp in range(52)]
    return [max(1, round(v * 256)) for v in lam], [max(1, round(math.sqrt(v) * 256)) for v in lam]


def md5_t():
    return [int(abs(math.sin(i + 1)) * 4294967296.0) & 0xFFFFFFFF for i in range(64)]


def crc(values):
    return zlib.crc32(b"".join(struct.pack("<i", v - (1 << 32) if v >= 1 << 31 else v) for v in values))


def kotlin(name, doc, values, hexa=False):
    lines = [f"    /** {doc} CRC-32 0x{crc(values):08X}. */", f"    val {name}: IntArray = intArrayOf("]
    per = 8 if hexa else 16
    for i in range(0, len(values), per):
        chunk = values[i:i + per]
        if hexa:
            lines.append("        " + ", ".join(f"0x{v:08x}.toInt()" for v in chunk) + ",")
        else:
            lines.append("        " + ", ".join(str(v) for v in chunk) + ",")
    lines.append("    )")
    return "\n".join(lines)


def main():
    lam, sqrt_lam = lambdas()
    print("package io.github.yuroyami.imagekodec.heic")
    print()
    print("// Generated by tools/hevc_encoder_tables.py. Do not edit by hand: HevcEncoderTest checks each CRC-32.")
    print()
    print("/** The constant tables of the HEVC encoder; tools/hevc_encoder_tables.py says where each comes from. */")
    print("internal object HevcEncoderTables {")
    print(kotlin("BIT_COST", "The cost in 1/256 bits of a bin in CABAC state s: index 2 * s for the MPS, 2 * s + 1 for the LPS.", bit_cost()))
    print()
    print(kotlin("LAMBDA_Q8", "The Lagrange multiplier of each QP of an 8-bit picture, in 1/256.", lam))
    print()
    print(kotlin("SQRT_LAMBDA_Q8", "The square root of [LAMBDA_Q8], in 1/256.", sqrt_lam))
    print()
    print(kotlin("MD5_T", "The sine table of RFC 1321, 3.4.", md5_t(), hexa=True))
    print("}")


if __name__ == "__main__":
    main()

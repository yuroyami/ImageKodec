#!/usr/bin/env python3
"""
Writes HtVlcTables.kt, the two CxtVLC code tables of the HTJ2K cleanup pass (ITU-T T.814):
for each context, significance pattern rho, u_off and EMB pattern (e_k, e_1), the
codeword and its length. The standard gives them as tables, and nothing derives them.

No copy of T.814 was at hand when the HT block coder was written, so this script recovers the
tables from the installed OpenJPEG library (libopenjp2 2.5.0, BSD-2-Clause), whose HT decoder
holds them as two 1024-entry lookups, one entry for each context and each 7 bits of input. An
entry packs rho, u_off, e_k, e_1 and the codeword length; the codeword is the low `length` bits
of the input. The script finds the two lookups by their shape alone (every entry agrees with
the entries that share its codeword), turns each back into the rows of the standard's table,
and writes those rows. Nothing of OpenJPEG's code is used, only the table data the standard
defines; the decoder and the encoder build their own lookups from the rows.

The lookup of the first line-pair has more distinct rows than the other (444 against 358), which
is how the script tells them apart. `Jp2HtOracleTest` holds the result to `opj_decompress`:
swapping or damaging a table fails it.

    python3 tools/htj2k_vlc_tables.py /usr/lib/x86_64-linux-gnu/libopenjp2.so.2.5.0 > \\
        imagekodec/src/io/github/yuroyami/imagekodec/codec/HtVlcTables.kt
"""
import hashlib
import struct
import sys


def lookups(data):
    """Offsets of every 2048-byte run that reads as a complete 8-context prefix-code lookup."""
    found = []
    for off in range(0, len(data) - 2048, 2):
        w = struct.unpack_from('<1024H', data, off)
        if all(0 < (x & 7) and w[(i & ~127) | ((i & 127) & ((1 << (x & 7)) - 1))] == x for i, x in enumerate(w)):
            found.append(off)
    # A run that starts one context, or one entry, into a table, or across two adjacent tables,
    # passes too: keep the first run, then the first one past its end, and so on.
    starts = []
    for o in found:
        if not starts or o >= starts[-1] + 2048:
            starts.append(o)
    return starts


def rows(data, off):
    w = struct.unpack_from('<1024H', data, off)
    out = set()
    for c in range(8):
        for i in range(128):
            x = w[c * 128 + i]
            length = x & 7
            out.add((c, (x >> 4) & 15, (x >> 3) & 1, x >> 12, (x >> 8) & 15, i & ((1 << length) - 1), length))
    return sorted(out)


def main():
    path = sys.argv[1]
    data = open(path, 'rb').read()
    starts = lookups(data)
    tables = [rows(data, o) for o in starts]
    if len(tables) != 2:
        sys.exit(f'expected two lookups, found {len(tables)} at {[hex(o) for o in starts]}')
    initial, later = sorted(tables, key=len, reverse=True)
    for t in (initial, later):
        # Context 0 codes a quad only after MEL said it is significant: no rho of 0 there.
        if any(r[0] == 0 and r[1] == 0 for r in t):
            sys.exit('a context-0 row with rho 0')
    sha = hashlib.sha256(data).hexdigest()

    def emit(name, t, doc):
        print(f'    /** {doc} */')
        print(f'    val {name}: IntArray = intArrayOf(')
        packed = [(c << 23) | (rho << 19) | (u << 18) | (ek << 14) | (e1 << 10) | (cw << 3) | n for c, rho, u, ek, e1, cw, n in t]
        for k in range(0, len(packed), 8):
            print('        ' + ' '.join('0x%07x,' % v for v in packed[k:k + 8]))
        print('    )')

    print('package io.github.yuroyami.imagekodec.codec')
    print()
    print('// Generated by tools/htj2k_vlc_tables.py; do not edit. Read from ' + path.rsplit('/', 1)[-1])
    print(f'// (SHA-256 {sha}).')
    print()
    print('/**')
    print(' * The CxtVLC tables of ITU-T T.814, one row a codeword: bits 23 to 25 hold the context,')
    print(' * 19 to 22 the significance pattern rho, 18 u_off, 14 to 17 e_k, 10 to 13 e_1, 3 to 9 the')
    print(' * codeword, first bit lowest, and 0 to 2 its length. [HtVlc] builds the lookups from them.')
    print(' */')
    print('internal object HtVlcTables {')
    emit('INITIAL', initial, 'The codewords of the first line-pair of a code-block.')
    print()
    emit('LATER', later, 'The codewords of every later line-pair.')
    print('}')


main()

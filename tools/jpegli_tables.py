#!/usr/bin/env python3
"""
Writes JpegliTables.kt, the constant tables of the Jpegli JPEG encoder port (#133), from
jpegli's own source, so no table is typed by hand.

Jpegli's quantization matrices, the 4:2:0 chroma rescale, the exponents of its non-linear
distance scaling and its zero-bias tables are fitted data: nothing derives them, so they are
copied, and this script is the only way they enter the tree. It reads the arrays from
lib/jpegli/quant.cc of a jpegli checkout at the commit pyjpegli 0.3.2 is built from (the oracle
of JpegliOracleTest), checks each one's length, and writes each value as the float32 the C
compiler stores, with the SHA-256 of the file and the CRC-32 of every table.
JpegliTablesTest holds the Kotlin file to those CRCs, so an edit by hand fails.

    git clone https://github.com/google/jpegli && git -C jpegli checkout 031a0077f5799a6041004267fc12b956c1f52a20
    python3 tools/jpegli_tables.py jpegli > \\
        imagekodec/src/io/github/yuroyami/imagekodec/codec/jpegli/JpegliTables.kt

jpegli is under the BSD-3-Clause license; the generated file keeps its notice.
"""
import hashlib
import re
import struct
import sys
import zlib

COMMIT = "031a0077f5799a6041004267fc12b956c1f52a20"
SOURCE = "lib/jpegli/quant.cc"

# name in the Kotlin file, C array name, expected element count, description
TABLES = [
    ("BASE_QUANT_MATRIX_YCBCR", "kBaseQuantMatrixYCbCr", 3 * 64,
     "Base quantization matrices for Y, Cb and Cr, natural order, before the global scale."),
    ("RESCALE_420", "k420Rescale", 64,
     "Extra scale of each chroma coefficient when the chroma is subsampled 4:2:0."),
    ("EXPONENT", "kExponent", 64,
     "Exponent of the distance in each coefficient's scale above distance 1.5."),
    ("ZERO_BIAS_MUL_LQ", "kZeroBiasMulYCbCrLQ", 3 * 64,
     "Zero-bias multipliers of Y, Cb and Cr at distance 3 and above."),
    ("ZERO_BIAS_MUL_HQ", "kZeroBiasMulYCbCrHQ", 3 * 64,
     "Zero-bias multipliers of Y, Cb and Cr at distance 1 and below."),
    ("ZERO_BIAS_OFFSET_AC", "kZeroBiasOffsetYCbCrAC", 3,
     "Zero-bias offset of the AC coefficients of Y, Cb and Cr."),
]


def array_values(source, name):
    match = re.search(r"\b" + re.escape(name) + r"\s*\[[^=]*\]\s*=\s*\{", source)
    if not match:
        sys.exit(f"{name}: not found")
    end = source.index("}", match.end())
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", source[match.end():end], flags=re.S)
    return [float(v.rstrip("f")) for v in re.findall(r"-?\d+\.\d*(?:[eE][-+]?\d+)?f?", body)]


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: jpegli_tables.py JPEGLI_CHECKOUT")
    with open(f"{sys.argv[1].rstrip('/')}/{SOURCE}", "rb") as f:
        data = f.read()
    source = data.decode("utf-8")
    out = []
    w = out.append
    w("// Generated by tools/jpegli_tables.py from google/jpegli at commit " + COMMIT + ".")
    w("// Do not edit: run the script.")
    w("//")
    w("// Copyright (c) the JPEG XL Project Authors. All rights reserved.")
    w("// Use of the original source is governed by a BSD-style license; see NOTICE.")
    w("//")
    w(f"// {SOURCE} sha256 {hashlib.sha256(data).hexdigest()}")
    w("")
    w("package io.github.yuroyami.imagekodec.codec.jpegli")
    w("")
    w("/** The Jpegli encoder's constant tables, as `" + SOURCE + "` holds them, each value a float32. */")
    w("internal object JpegliTables {")
    for kotlin, c_name, count, doc in TABLES:
        values = array_values(source, c_name)
        if len(values) != count:
            sys.exit(f"{c_name}: {len(values)} values, expected {count}")
        packed = b"".join(struct.pack(">f", v) for v in values)
        hexed = packed.hex()
        w("")
        w(f"    /** {doc} `{c_name}`. */")
        w(f"    val {kotlin}: DoubleArray = floats(")
        for i in range(0, len(hexed), 96):
            w(f'        "{hexed[i:i + 96]}" +')
        out[-1] = out[-1][:-2] + ","
        w("    )")
        w("")
        w(f"    /** CRC-32 of [{kotlin}] as jpegli holds it, four big-endian bytes of float32 a value. */")
        w(f"    const val {kotlin}_CRC32: Long = 0x{zlib.crc32(packed):08X}L")
    w("")
    w("    /** The float32 values of [hex], eight digits a value, widened to Double without rounding. */")
    w("    private fun floats(hex: String): DoubleArray =")
    w("        DoubleArray(hex.length / 8) { Float.fromBits(hex.substring(it * 8, it * 8 + 8).toLong(16).toInt()).toDouble() }")
    w("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
